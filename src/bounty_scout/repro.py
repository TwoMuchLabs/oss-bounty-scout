# Commands from an issue that would test something other than the checkout under bisect.
_SKIPPED_COMMANDS = re.compile(
    r"^\s*(?:sudo\b|git\s+(?:clone|checkout|pull|fetch)\b|cd\s|pip3?\s+install\b|python3?\s+-m\s+pip\s+install\b"
    r"|npm\s+(?:i|install|ci)\b|yarn\s+(?:add|install)\b|apt(?:-get)?\s|brew\s|conda\s|docker\s)"
)


@dataclass
class ReproPlan:
    source: str  # "test-cmd" | "python-snippet" | "node-snippet" | "shell-steps"
    command: str  # may contain {test_file}
    test_filename: str | None = None
    test_content: str | None = None
    signature: str | None = None
    uses_issue_code: bool = False
    notes: list[str] = field(default_factory=list)
    snippet: str | None = None  # the reporter's code, before any imports are added


@dataclass
class CheckSpec:
    """Everything needed to judge a commit; serialisable so ``git bisect run`` can load it."""

    command: str
    setup: str | None = None
    signature_pattern: str | None = None
    signature: str | None = None
    strict: bool = False  # once the reported line itself has been seen, look-alikes no longer count
    timeout: float = 120
    sandbox: str = "worktree"
    repro_dir: str | None = None
    docker_image: str = "python:3.12-slim"
    docker_network: str = "none"
    pass_env: list[str] = field(default_factory=list)
    log_path: str | None = None
    max_skips: int = 20  # give up bisecting once this many commits in the range could not be tested

    def dump(self, path: str | Path) -> None:
        Path(path).write_text(json.dumps(asdict(self), indent=2))

    @classmethod
    def load(cls, path: str | Path) -> "CheckSpec":
        return cls(**json.loads(Path(path).read_text()))


@dataclass
class Verdict:
    status: str  # good | bad | skip
    reason: str
    result: RunResult


def signature_pattern(signature: str | None) -> str | None:
    """Regex for an error line that tolerates changing numbers, addresses and long tails."""
    if not signature:
        return None
    text = " ".join(signature.split())[:160]
    parts = re.split(r"(0x[0-9a-fA-F]+|\d+)", text)
    out = []
    for part in parts:
        if re.fullmatch(r"0x[0-9a-fA-F]+", part):
            out.append(r"0x[0-9a-fA-F]+")
        elif part.isdigit():
            out.append(r"\d+")
        else:
            out.append(re.escape(part).replace(r"\ ", r"\s+"))
    return "".join(out)


def _python_test(number: int, snippet: str, imports: list[str] | None = None) -> str:
    """The reporter's snippet, run as a script exactly as they wrote it.

    It is deliberately not wrapped in a function: that changes scoping and the
    qualified names that appear in error messages, and the error would no
    longer match the one that was reported.
    """
    header = f"# Regression test for issue #{number}, generated by oss-bounty-scout from the reporter's snippet.\n"
    added = "".join(f"{line}  # added: the snippet left this import out\n" for line in imports or [])
    return f"{header}{added}{snippet.rstrip()}\n"


def _compiles(text: str) -> bool:
    try:
        compile(text, "<issue>", "exec")
        return True
    except (SyntaxError, ValueError):
        return False


def _is_version_boilerplate(code: str) -> bool:
    """Issue templates ask for ``print(pkg.__version__, sys.version, sys.platform)``. That is not the reproduction."""
    tree = ast.parse(code)
    rest = [n for n in tree.body if not isinstance(n, (ast.Import, ast.ImportFrom))]
    if not rest or len(rest) > 3:
        return False
    return all(isinstance(n, ast.Expr) and isinstance(n.value, ast.Call) and getattr(n.value.func, "id", "") == "print"
               and re.search(r"__version__|sys\.version|sys\.platform|platform\.", ast.unparse(n)) for n in rest)


def _pick_block(issue: ParsedIssue, kind: str):
    blocks = [b for b in issue.code_blocks if b.kind == kind]
    ordered = [b for b in blocks if b.section == "repro"] + [b for b in blocks if b.section != "repro"]
    if kind == "python":  # reporters often paste indented or partial code; take the first block that is valid Python
        for block in ordered:
            block.text = textwrap.dedent(block.text)
        ordered = [b for b in ordered if _compiles(b.text)]
        real = [b for b in ordered if not _is_version_boilerplate(b.text)]
        ordered = real or ordered
    return ordered[0] if ordered else None


def _runs_own_tests(tree: ast.Module, tests: list) -> bool:
    called = {n.func.id for n in ast.walk(tree) if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)}
    return any(t.name in called for t in tests) or "pytest" in called or "main" in called


def _needs_pytest(tests: list, classes: list) -> bool:
    """Test classes, and test functions with arguments or decorators, only work under pytest."""
    return bool(classes) or any(
        t.args.args or t.args.kwonlyargs or t.decorator_list or isinstance(t, ast.AsyncFunctionDef) for t in tests)


def _pytest_style(snippet: str, pytest_output: bool = False) -> tuple[str, str, str | None]:
    """A snippet that only *defines* ``test_`` functions does nothing when run as a script.

    Call them ourselves when they take no arguments; otherwise they need pytest's fixtures.
    """
    as_written = (snippet, "python3 {test_file}", None)
    try:
        tree = ast.parse(snippet)
    except (SyntaxError, ValueError):
        return as_written
    tests = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and n.name.startswith("test")]
    classes = [n for n in tree.body if isinstance(n, ast.ClassDef) and n.name.startswith("Test")]
    if not (tests or classes) or _runs_own_tests(tree, tests):
        return as_written
    if _needs_pytest(tests, classes):
        if not pytest_output:
            return as_written  # nothing says the reporter used pytest: run it the way it reads
        return (snippet, "python3 -m pytest -q -x -p no:cacheprovider {test_file}",
                "The snippet defines tests that need pytest (fixtures, parameters or classes), so it was run with pytest.")
    calls = "\n".join(f"{t.name}()" for t in tests)
    return (f"{snippet.rstrip()}\n\n# added: the snippet defines these tests but never calls them\n{calls}\n", as_written[1],
            "The snippet only defined test functions, so calls to them were added: " + ", ".join(f"`{t.name}()`" for t in tests) + ".")


_PY_COMMAND = re.compile(r"^(?:python[\d.]*|py)\s+(?:-[A-Za-z]\s+)*[\w./\\-]+\.py\b[ \t]*(?P<args>.*)$")


def _python_plan(issue: ParsedIssue, code: str, signature: str | None) -> ReproPlan:
    snippet, command, note = _pytest_style(code, issue.pytest_output)
    plan = ReproPlan("python-snippet", command, f"test_issue_{issue.number}.py",
                     _python_test(issue.number, snippet), signature, uses_issue_code=True, snippet=snippet)
    if note:
        plan.notes.append(note)
    for command in issue.shell_commands:  # "python app.py --flag": keep the reporter's arguments
        m = _PY_COMMAND.match(command.strip())
        if m and m.group("args"):
            plan.command = f"python3 {{test_file}} {m.group('args')}"
            plan.notes.append(f"Ran the snippet with the arguments from the report: `{m.group('args')}`.")
            break
    return plan


def _node_plan(number: int, code: str, signature: str | None) -> ReproPlan:
    content = f"// Regression test for issue #{number}, generated by oss-bounty-scout from the reporter's snippet.\n{code}\n"
    # "import x from 'pkg'" needs an ES module; "require('pkg')" needs CommonJS. The extension settles it,
    # whatever the project's own package.json says about files in its tree.
    extension = "mjs" if _ESM.search(code) and "require(" not in code else "cjs"
    return ReproPlan("node-snippet", "node {test_file}", f"test_issue_{number}.{extension}", content, signature, uses_issue_code=True)


def _shell_plan(issue: ParsedIssue, signature: str | None) -> ReproPlan | None:
    kept = [c for c in issue.shell_commands if not _SKIPPED_COMMANDS.match(c)]
    if not kept:
        return None
    dropped = [c for c in issue.shell_commands if _SKIPPED_COMMANDS.match(c)]
    notes = [f"Skipped `{c}` (install/navigation step; the checkout under test is used instead)." for c in dropped]
    content = (f"# Reproduction for issue #{issue.number}, generated by oss-bounty-scout from the reporter's steps.\nset -e\n"
               + "\n".join(kept) + "\n")
    return ReproPlan("shell-steps", "sh {test_file}", f"repro_issue_{issue.number}.sh", content, signature, uses_issue_code=True, notes=notes)


def build_plan(issue: ParsedIssue, test_cmd: str | None = None, match: str | None = None) -> ReproPlan | None:
    """Choose how to reproduce: a maintainer-supplied command wins, then issue code."""
    signature = match or issue.error_signature
    if test_cmd:
        # A maintainer command is judged by exit code unless they also pass --match.
        return ReproPlan("test-cmd", test_cmd, signature=match)
    block = _pick_block(issue, "python")
    if block:
        return _python_plan(issue, block.text, signature)
    block = _pick_block(issue, "javascript")
    if block:
        return _node_plan(issue.number, block.text, signature)
    return _shell_plan(issue, signature)


# --- imports the reporter left out -------------------------------------------------

_SKIP_DIRS = {"tests", "test", "testing", "docs", "doc", "examples", "example", "benchmarks", "build", "dist", "node_modules"}
_SKIP_MODULES = {"setup", "conftest", "noxfile", "tasks", "fabfile"}


def missing_names(code: str) -> list[str]:
    """Names the snippet reads but never binds (and that are not builtins), in first-use order."""
    try:
        tree = ast.parse(code)
    except (SyntaxError, ValueError):
        return []
    bound: set[str] = set(dir(builtins))
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and any(a.name == "*" for a in node.names):
            return []  # a star import could bind anything
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update((a.asname or a.name).split(".")[0] for a in node.names)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            bound.add(node.name)
        elif isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
            bound.add(node.id)
        elif isinstance(node, ast.arg):
            bound.add(node.arg)
        elif isinstance(node, ast.ExceptHandler) and node.name:
            bound.add(node.name)
        elif isinstance(node, (ast.MatchAs, ast.MatchStar)) and node.name:
            bound.add(node.name)
        elif isinstance(node, ast.MatchMapping) and node.rest:
            bound.add(node.rest)
    loads = sorted((n for n in ast.walk(tree) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)),
                   key=lambda n: (n.lineno, n.col_offset))
    return [name for name in dict.fromkeys(n.id for n in loads) if name not in bound]


def project_index(root: Path, max_files: int = 1500) -> tuple[set[str], dict[str, list[tuple[str, bool]]]]:
    """Top-level importable names, and for each top-level name in the project's modules: (module, is_definition).

    Read statically with ``ast``; nothing from the project is imported or run.
    """
    top: set[str] = set()
    exports: dict[str, list[tuple[str, bool]]] = {}
    seen = 0
    for base in (root / "src", root):
        if not base.is_dir():
            continue
        for child in sorted(base.iterdir()):
            if child.name.startswith((".", "_")):
                continue
            if child.is_dir() and (child / "__init__.py").exists() and child.name not in _SKIP_DIRS:
                files = sorted(p for p in child.rglob("*.py") if not (_SKIP_DIRS & set(p.relative_to(base).parts)))
            elif child.is_file() and child.suffix == ".py" and child.stem not in _SKIP_MODULES:
                files = [child]
            else:
                continue
            top.add(child.stem if child.is_file() else child.name)
            for file in files:
                seen += 1
                if seen > max_files:
                    return top, exports
                rel = file.relative_to(base).with_suffix("")
                module = ".".join(rel.parts[:-1] if rel.name == "__init__" else rel.parts)
                try:
                    tree = ast.parse(file.read_text(errors="replace"))
                except (SyntaxError, ValueError, OSError):
                    continue
                for node in tree.body:
                    names: list[tuple[str, bool]] = []
                    if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                        names.append((node.name, True))
                    elif isinstance(node, ast.Assign):
                        names += [(t.id, True) for t in node.targets if isinstance(t, ast.Name)]
                    elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                        names.append((node.target.id, True))
                    elif isinstance(node, ast.ImportFrom):
                        names += [(a.asname or a.name, False) for a in node.names if a.name != "*"]
                    for name, defined in names:
                        if not name.startswith("_"):
                            exports.setdefault(name, []).append((module, defined))
    return top, exports


# Names people use without importing, where the intent is not in doubt.
_KNOWN_NAMES = {
    **dict.fromkeys(("Any Optional Union List Dict Tuple Set FrozenSet Callable Iterable Iterator Sequence Mapping "
                     "TypeVar Generic ClassVar Final Literal Protocol NamedTuple TypedDict Type Annotated cast overload "
                     "TYPE_CHECKING").split(), "typing"),
    **dict.fromkeys(("Path", "PurePath"), "pathlib"),
    **dict.fromkeys(("OrderedDict", "defaultdict", "namedtuple", "Counter", "deque"), "collections"),
    **dict.fromkeys(("Enum", "IntEnum", "auto"), "enum"),
    **dict.fromkeys(("partial", "wraps", "lru_cache", "cached_property"), "functools"),
    **dict.fromkeys(("StringIO", "BytesIO"), "io"),
    **dict.fromkeys(("ABC", "abstractmethod"), "abc"),
    **dict.fromkeys(("timedelta", "timezone", "date"), "datetime"),
    "dataclass": "dataclasses", "Decimal": "decimal", "Fraction": "fractions",
}


def _usage(code: str) -> tuple[set[str], dict[str, set[str]]]:
    """Names called directly, and the attributes read off each bare name."""
    called: set[str] = set()
    attrs: dict[str, set[str]] = {}
    for node in ast.walk(ast.parse(code)):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            called.add(node.func.id)
        elif isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            attrs.setdefault(node.value.id, set()).add(node.attr)
    return called, attrs


def _stdlib_import(name: str, called: set[str], used: set[str]) -> str:
    """``import datetime`` or ``from datetime import datetime``? Decide from how the name is used."""
    try:
        module = importlib.import_module(name)  # standard library only: safe to import
    except Exception:
        return f"import {name}"
    member = getattr(module, name, None)
    if member is not None and (name in called or any(not hasattr(module, a) and hasattr(member, a) for a in used)):
        return f"from {name} import {name}"
    return f"import {name}"


def resolve_imports(names: list[str], top: set[str], exports: dict[str, list[tuple[str, bool]]], code: str = "") -> list[str]:
    lines = []
    called, attrs = _usage(code) if code else (set(), {})
    modules = {m for found in exports.values() for m, _ in found}
    for name in names:
        if name in top:
            lines.append(f"import {name}")
            # "pkg.sub.thing" needs "import pkg.sub" unless the package imports the submodule itself.
            lines += [f"import {name}.{a}" for a in sorted(attrs.get(name, ())) if f"{name}.{a}" in modules]
        elif name in sys.stdlib_module_names:
            lines.append(_stdlib_import(name, called, attrs.get(name, set())))
        elif name not in exports and name in _KNOWN_NAMES:
            lines.append(f"from {_KNOWN_NAMES[name]} import {name}")
        elif name in exports:
            # Prefer the public face: a top-level package that exposes the name, else the shallowest definition.
            public = [m for m, _ in exports[name] if m in top]
            defined = sorted((m for m, d in exports[name] if d), key=lambda m: (m.count("."), m))
            module = (public or defined or [exports[name][0][0]])[0]
            lines.append(f"from {module} import {name}")
    return lines


def complete_imports(plan: ReproPlan, worktree: str | Path) -> None:
    """Add imports for names the snippet uses without importing, when the project or stdlib clearly provides them."""
    if plan.source != "python-snippet" or not plan.snippet:
        return
    names = missing_names(plan.snippet)
    top, exports = project_index(Path(worktree))
    lines = resolve_imports(names, top, exports, plan.snippet) if names else []
    # "import pkg" followed by "pkg.sub.thing" fails unless the package imports that submodule itself.
    try:
        tree = ast.parse(plan.snippet)
    except (SyntaxError, ValueError):
        tree = None
    if tree:
        _, attrs = _usage(plan.snippet)
        modules = {m for found in exports.values() for m, _ in found}
        imported = {a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names if not a.asname}
        for name in sorted(imported & top):
            lines += [f"import {name}.{a}" for a in sorted(attrs.get(name, ())) if f"{name}.{a}" in modules]
    lines = list(dict.fromkeys(lines))
    if lines:
        number = int(re.search(r"\d+", plan.test_filename).group())
        plan.test_content = _python_test(number, plan.snippet, lines)
        plan.notes.append("Added imports the snippet left out: " + ", ".join(f"`{l}`" for l in lines) + ".")


# Loaded with ``node -r``: makes ``require('<this package>')`` resolve to the checkout under test,
# the way it would for someone who installed the package, without touching the checkout.
NODE_ALIAS = """const Module = require('module');
const path = require('path');
let name;
try { name = require(path.join(process.cwd(), 'package.json')).name; } catch (e) {}
if (name) {
  const resolve = Module._resolveFilename;
  Module._resolveFilename = function (request, ...rest) {
    if (request === name) request = process.cwd();
    else if (request.startsWith(name + '/')) request = path.join(process.cwd(), request.slice(name.length + 1));
    return resolve.call(this, request, ...rest);
  };
}
"""


# The same for ``import ... from '<this package>'``. Loaded with ``node --import``.
NODE_REGISTER = """import { register } from 'node:module';
register('./scout_hooks.mjs', import.meta.url);
"""
NODE_HOOKS = """import { createRequire } from 'node:module';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const cwd = process.cwd();
const require = createRequire(path.join(cwd, 'package.json'));
let name;
try { name = require('./package.json').name; } catch (e) {}

export async function resolve(specifier, context, next) {
  if (name && (specifier === name || specifier.startsWith(name + '/'))) {
    const inside = { ...context, parentURL: pathToFileURL(path.join(cwd, 'package.json')).href };
    try {
      return await next(specifier, inside);  // a package may import itself by name when it declares "exports"
    } catch (e) {
      const target = specifier === name ? cwd : path.join(cwd, specifier.slice(name.length + 1));
      return next(pathToFileURL(require.resolve(target)).href, context);
    }
  }
  return next(specifier, context);
}
"""
_ESM = re.compile(r"^\s*import\s+(?:[\w*{}\s,$]+\s+from\s+)?['\"][^'\"]+['\"]|^\s*export\s", re.M)


def materialise(plan: ReproPlan, repro_dir: Path, sandbox: str) -> str:
    """Write the test file outside the worktree and return the concrete command."""
    if not plan.test_filename:
        return plan.command
    (repro_dir / plan.test_filename).write_text(plan.test_content or "")
    base = "/scout" if sandbox == "docker" else str(repro_dir)
    command = plan.command
    if plan.source == "node-snippet":
        (repro_dir / "scout_alias.cjs").write_text(NODE_ALIAS)
        (repro_dir / "scout_register.mjs").write_text(NODE_REGISTER)
        (repro_dir / "scout_hooks.mjs").write_text(NODE_HOOKS)
        command = command.replace("node {test_file}", f"node -r {base}/scout_alias.cjs --import {base}/scout_register.mjs {{test_file}}")
    return command.replace("{test_file}", f"{base}/{plan.test_filename}")


_ANSI = re.compile(r"\x1b\[[0-9;?]*[A-Za-z]")
_TYPED = re.compile(r"^\s*(?:Caused by:\s*|Uncaught\s+|E\s+|(?:FAILED|ERROR) \S+ - )?(?P<type>[A-Za-z_][\w.<>]*(?:Error|Exception|Failure|Exit|Interrupt))(?::[ \t]*(?P<msg>.*))?\s*$", re.M)
_NOISE = re.compile(r"0x[0-9a-fA-F]+|\d+|(?:[A-Za-z]:)?[/\\][\w./\\-]+|\b[\w.]+\.(?=[\w<]+\()|<locals>\.")


def _mask(message: str) -> str:
    """Drop what legitimately varies between runs: numbers, addresses, paths, qualified-name prefixes."""
    return " ".join(_NOISE.sub("", message.lower()).split())[:160]


def error_matches(signature: str | None, pattern: str | None, output: str) -> bool:
    return match_kind(signature, pattern, output) is not None


# No spaces inside the quotes: that keeps names ('os.path', 'value-1') and skips apostrophes in prose ("can't ... it's").
_QUOTED = re.compile(r"'([^'\s]{1,60})'|\"([^\"\s]{1,60})\"|`([^`\s]{1,60})`")


def _names_agree(want: str, got: str) -> bool:
    """Quoted names are the substance of a message: NameError 'tfds' is not NameError 'IProgress'."""
    a = {next(g for g in m if g) for m in _QUOTED.findall(want)}
    b = {next(g for g in m if g) for m in _QUOTED.findall(got)}
    if not a or not b:
        return True
    if len(a) <= 3 or len(b) <= 3:
        return a <= b or b <= a
    return len(a & b) / len(a | b) >= 0.5  # long, dict-like messages are cut off at different points


def match_kind(signature: str | None, pattern: str | None, output: str, strict: bool = False) -> str | None:
    """Is the reported error in this output, and how sure is the match?

    ``exact``: the reported line, allowing for changed numbers. ``similar``: the
    same exception type with a similar message, since Python versions reword
    messages and add qualified names, and paths differ between machines.
    ``type-only``: the same exception type, when that is all there is to compare.
    """
    text = _ANSI.sub("", output)
    if pattern and re.search(pattern, " ".join(text.split())):
        return "exact"
    wanted = _TYPED.match(signature or "")
    if not wanted or strict:
        return None
    want_type, want_msg = wanted.group("type").split(".")[-1], _mask(wanted.group("msg") or "")
    for found in _TYPED.finditer(text):
        if found.group("type").split(".")[-1] != want_type:
            continue
        got_msg = _mask(found.group("msg") or "")
        if not want_msg:
            if not plausible_exception(wanted.group("type"), None):
                return None
            return "type-only"  # the report gave only the exception type
        if got_msg and not _names_agree(wanted.group("msg") or "", found.group("msg") or ""):
            continue
        if not got_msg:
            # pytest prints the compared values ("assert 1 == 2"); a plain run of the same assert prints nothing.
            if want_type == "AssertionError" and want_msg.startswith("assert "):
                return "type-only"
            continue
        if want_msg in got_msg or got_msg in want_msg or difflib.SequenceMatcher(None, want_msg, got_msg).ratio() >= 0.6:
            return "similar"
        # Dict and set contents print in varying order: compare the words regardless of order.
        want_words, got_words = set(re.findall(r"\w+", want_msg)), set(re.findall(r"\w+", got_msg))
        if len(want_words) >= 6 and len(want_words & got_words) / len(want_words | got_words) >= 0.6:
            return "similar"
    return None


def classify(result: RunResult, pattern: str | None, signature: str | None = None, strict: bool = False) -> tuple[str, str]:
    if SETUP_FAILED in result.output and result.exit_code == 125:
        return SKIP, "setup command failed at this commit"
    if result.timed_out:
        return SKIP, "timed out"
    if pattern or signature:
        kind = match_kind(signature, pattern, result.output, strict)
        if kind:
            return BAD, {"exact": "reported error present in output",
                         "similar": "same error type with a similar message in output",
                         "type-only": "same error type in output; the report gave no message to compare"}[kind]
        if result.exit_code == 0:
            return GOOD, "exited 0 without the reported error"
        return SKIP, f"exited {result.exit_code} with a different failure"
    if result.exit_code == 0:
        return GOOD, "exited 0"
    return BAD, f"exited {result.exit_code}"


def evaluate(spec: CheckSpec, worktree: str | Path, clean: bool = True) -> Verdict:
    result = run_isolated(
        spec.command, worktree, setup=spec.setup, timeout=spec.timeout, sandbox=spec.sandbox,
        repro_dir=spec.repro_dir, docker_image=spec.docker_image, docker_network=spec.docker_network,
        pass_env=spec.pass_env,
    )
    status, reason = classify(result, spec.signature_pattern, spec.signature, spec.strict)
    if clean:
        reset_tree(worktree)
    return Verdict(status, reason, result)
